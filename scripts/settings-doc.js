#!/usr/bin/env node
// Writes the settings inventory of docs/settings.md (between the inventory markers) from ui/src/settings-model.js, so
// the document never drifts from the schema. `node scripts/settings-doc.js` updates it; `--check` exits 1 when it is
// out of date (test/settings-model.test.js runs the same comparison).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { CATEGORIES, HIDDEN, WRITERS } from '../ui/src/settings-model.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const DOC = path.join(ROOT, 'docs', 'settings.md');
export const START = '<!-- settings-inventory:start (generated by scripts/settings-doc.js — do not edit by hand) -->';
export const END = '<!-- settings-inventory:end -->';

const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const code = (s) => '`' + String(s).replace(/`/g, "'") + '`';
const valueText = (v) => (v && typeof v === 'object' ? v.label || v.value : v === '' ? '(empty)' : v);

function controlText(it) {
  if (it.values) return `${it.control}: ${it.values.map(valueText).join(' · ')}`;
  if (it.choices) return `${it.control}: ‹${it.choices}›`;
  if (it.min != null || it.max != null) return `${it.control} ${it.min}–${it.max}${it.unit ? ' ' + it.unit : ''}`;
  return it.control;
}

function whereText(it) {
  if (it.pref) {
    const p = it.pref;
    return `localStorage ${code(p.key)}${p.field ? ` › ${code(p.field)}` : ''}${p.dom ? ` (${code(p.dom)})` : ''}`;
  }
  if (it.config) return `${code(it.config)}${it.writer ? ` → ${code(WRITERS[it.writer].endpoint)}` : ''}`;
  if (it.action?.api) return code(it.action.api);
  return `opens ${code(it.action?.open)}`;
}

function defaultText(v) {
  if (v === undefined) return '';
  if (Array.isArray(v)) return v.length > 3 ? `[${v.length} items]` : code(JSON.stringify(v));
  return code(JSON.stringify(v));
}

function notesText(it) {
  return [
    defaultText(it.default) && `default ${defaultText(it.default)}`,
    it.readOnly && 'read-only', it.secret && 'secret', it.restart && 'after restart', it.reload && 'after reload',
    it.phone === false && 'not on phones', it.env && `env ${code(it.env)}`, it.cli && code(it.cli), it.action?.confirm && 'confirms first',
  ].filter(Boolean).join(' · ');
}

/** The generated part of docs/settings.md. */
export function renderInventory() {
  const out = ['### Writers', '', 'Each writable config item is saved by the writer whose prefix is the longest match of its path.', '',
    '| Writer | Config prefix | Endpoint it mirrors | Setter | Reads with |', '| --- | --- | --- | --- | --- |'];
  for (const [k, w] of Object.entries(WRITERS)) out.push(`| ${code(k)} | ${w.prefix ? code(w.prefix) : '(everything else)'} | ${code(w.endpoint)} | ${cell(w.setter)}${w.whole ? ` · whole object: ${w.whole.join(', ')}` : ''}${w.note ? ` · ${cell(w.note)}` : ''} | ${cell(w.read)} |`);
  out.push('');
  for (const c of CATEGORIES) {
    out.push(`### ${c.icon} ${c.label}`, '', c.help, '', '| Setting | Control | Scope | Lives in | Notes |', '| --- | --- | --- | --- | --- |');
    for (const it of c.items) out.push(`| ${cell(`${it.group ? `${it.group} › ` : ''}**${it.label}** ${code(it.id)}`)} | ${cell(controlText(it))} | ${it.scope} | ${cell(whereText(it))} | ${cell(notesText(it))} |`);
    out.push('');
  }
  out.push('### Hidden on purpose', '', '| Config path / localStorage key | Why it is not in the window |', '| --- | --- |');
  for (const h of HIDDEN) out.push(`| ${h.config ? `config ${code(h.config)}` : h.pref ? `localStorage ${code(h.pref)}` : `localStorage ${code(h.prefPrefix + '*')}`} | ${cell(h.reason)} |`);
  return out.join('\n');
}

/** The document with its inventory section replaced. */
export function withInventory(doc) {
  const a = doc.indexOf(START);
  const b = doc.indexOf(END);
  if (a < 0 || b < a) throw new Error(`docs/settings.md has no inventory markers (${START} … ${END})`);
  return `${doc.slice(0, a + START.length)}\n${renderInventory()}\n${doc.slice(b)}`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const doc = fs.readFileSync(DOC, 'utf8');
  const next = withInventory(doc);
  if (process.argv.includes('--check')) {
    if (next !== doc) { console.error('docs/settings.md is out of date: run node scripts/settings-doc.js'); process.exit(1); }
    console.log('docs/settings.md inventory is up to date');
  } else if (next !== doc) { fs.writeFileSync(DOC, next); console.log('docs/settings.md inventory updated'); } else console.log('docs/settings.md inventory already up to date');
}
